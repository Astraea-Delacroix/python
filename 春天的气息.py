from turtle import *      # 导入 turtle 绘图库所有功能
from random import random # 导入随机数生成函数

tracer(50)                # 控制绘图刷新频率，加快渲染速度
bgcolor('black')          # 设置背景为黑色
hideturtle()              # 隐藏画笔图标
color('#43ff26')          # 设置蕨叶的颜色为亮绿色

x, y = 0, 0               # 定义迭代的初始坐标（原点）

for _ in range(9000):     # 循环9000次，生成蕨叶上的点
    r = random()          # 生成一个0~1的随机数，用于选择变换规则
    if r < 0.01:          # 1%概率：蕨叶的茎干
        x, y = 0, 0.16 * y
    elif r < 0.86:        # 85%概率：蕨叶的主叶片
        x, y = 0.85*x + 0.04*y, -0.04*x + 0.85*y + 1.6
    elif r < 0.93:        # 7%概率：左侧小叶片
        x, y = 0.2*x - 0.26*y, 0.23*x + 0.22*y + 1.6
    else:                 # 7%概率：右侧小叶片
        x, y = -0.15*x + 0.28*y, 0.26*x + 0.24*y + 0.44
    up()                  # 抬起画笔，避免移动时画线
    goto(x*50 , y*50 - 250) # 坐标放大并调整位置，让蕨叶居中
    dot(3)                # 在当前位置画一个3像素的点
done()                   # 保持绘图窗口打开